# lib/monitors.sh — monitor order (left → right) and which workspaces live on which monitor.
#
# Saved in state.conf (monitors are matched by their description, so swapping cables doesn't matter):
#   MONITORS="desc|x;desc|x"   left to right, with each one's x position in pixels
#   MON_WS="1-5;6-10"          workspaces for each monitor, same order (empty = no rule)
# Written to ~/.config/hypr/monitors.lua, which hyprland.lua loads.

WB_MAX_WS=10   # the keybinds cover workspaces 1-10

# Connected monitors, one per line: description<TAB>port<TAB>model<TAB>logical width
mon_connected() {
    command -v hyprctl > /dev/null || return 0
    hyprctl monitors all -j 2> /dev/null | jq -r '.[] |
        (if (.transform % 2) == 1 then .height else .width end) as $w |
        "\(.description)\t\(.name)\t\(.model // .description)\t\(($w / .scale) | round)"' 2> /dev/null || true
}

# Split the saved settings into arrays: MON_DESC[] MON_X[] MON_WSL[]
mon_parse() {
    MON_DESC=(); MON_X=(); MON_WSL=()
    local IFS=';' e
    local -a mons=() wss=()
    read -ra mons <<< "$MONITORS"
    read -ra wss <<< "$MON_WS"
    local i; for i in "${!mons[@]}"; do
        e="${mons[$i]}"; [[ -n "$e" ]] || continue
        MON_DESC+=("${e%|*}"); MON_X+=("${e##*|}"); MON_WSL+=("${wss[$i]:-}")
    done
}

# ws_expand "1-5 7" -> "1 2 3 4 5 7"; fails on anything that isn't a workspace 1-10
ws_expand() {
    local out=() part a b n
    for part in ${1//,/ }; do
        if [[ "$part" =~ ^([0-9]+)-([0-9]+)$ ]]; then a=${BASH_REMATCH[1]}; b=${BASH_REMATCH[2]}
        elif [[ "$part" =~ ^[0-9]+$ ]]; then a=$part; b=$part
        else return 1; fi
        (( a >= 1 && b <= WB_MAX_WS && a <= b )) || return 1
        for (( n = a; n <= b; n++ )); do out+=("$n"); done
    done
    echo "${out[*]}"
}

lbl_monitors() {
    mon_parse
    if (( ${#MON_DESC[@]} < 2 )); then echo "Monitors     auto · arrange monitors and their workspaces"; return; fi
    local parts=() i model
    for i in "${!MON_DESC[@]}"; do
        model=$(mon_connected | awk -F'\t' -v d="${MON_DESC[$i]}" '$1 == d { print $3; exit }')
        parts+=("${model:-?}${MON_WSL[$i]:+ [${MON_WSL[$i]}]}")
    done
    local IFS='|'; local s="${parts[*]}"
    echo "Monitors     ${s//|/ · } (left → right)"
}

# Writes ~/.config/hypr/monitors.lua from the saved settings
write_monitors_lua() {
    mon_parse
    local f="$HOME/.config/hypr/monitors.lua" i ws first
    mkdir -p "$(dirname "$f")"
    {
        echo "-- ~/.config/hypr/monitors.lua — generated by Waterbear (menu → Monitors). Don't edit:"
        echo "-- it's rewritten on every change. Put your own monitor settings in ~/.config/hypr/user.lua."
        for i in "${!MON_DESC[@]}"; do
            printf 'hl.monitor({ output = "desc:%s", mode = "preferred", position = "%sx0", scale = "auto" })\n' \
                "${MON_DESC[$i]}" "${MON_X[$i]}"
        done
        echo '-- Any other monitor (a projector, a laptop screen): best mode, placed automatically'
        echo 'hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "auto" })'
        for i in "${!MON_DESC[@]}"; do
            [[ -n "${MON_WSL[$i]}" ]] || continue
            first=1
            for ws in $(ws_expand "${MON_WSL[$i]}" || true); do
                # the first workspace in each list is the one the monitor shows at login
                printf 'hl.workspace_rule({ workspace = "%s", monitor = "desc:%s"%s })\n' \
                    "$ws" "${MON_DESC[$i]}" "$( (( first )) && echo ", default = true")"
                first=0
            done
        done
    } > "$f"
}

# Move workspaces that are already open onto their monitor (rules only apply to new workspaces)
mon_move_open_workspaces() {
    [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]] || return 0
    mon_parse
    local open i ws
    open=" $(hyprctl workspaces -j 2> /dev/null | jq -r '.[].id' 2> /dev/null | tr '\n' ' ') "
    for i in "${!MON_DESC[@]}"; do
        for ws in $(ws_expand "${MON_WSL[$i]}" || true); do
            [[ "$open" == *" $ws "* ]] || continue
            hyprctl dispatch "hl.dsp.workspace.move({ workspace = $ws, monitor = \"desc:${MON_DESC[$i]}\" })" > /dev/null 2>&1 || true
        done
    done
}

# ---------------------------------------------------------------------------
# Menu
# ---------------------------------------------------------------------------
pick_monitors() {  # sets MONITORS and MON_WS; returns 1 on esc / nothing to do
    local -a desc=() port=() model=() width=()
    local d p m w
    while IFS=$'\t' read -r d p m w; do
        [[ -n "$d" ]] || continue
        desc+=("$d"); port+=("$p"); model+=("$m"); width+=("$w")
    done < <(mon_connected)
    if (( ${#desc[@]} < 2 )); then
        warn "Only ${#desc[@]} monitor found$([[ -z "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]] && echo " (run this inside Hyprland)"). Plug in the second one, then try again."
        ui_pause; return 1
    fi
    mon_parse

    # Current order: saved order first (connected ones only), then any new monitors left to right as they are now
    local -a order=()
    local i
    for d in "${MON_DESC[@]}"; do
        for i in "${!desc[@]}"; do [[ "${desc[$i]}" == "$d" ]] && order+=("$i"); done
    done
    while IFS=$'\t' read -r _ p; do
        for i in "${!desc[@]}"; do
            [[ "${port[$i]}" == "$p" && " ${order[*]} " != *" $i "* ]] && order+=("$i")
        done
    done < <(hyprctl monitors all -j 2> /dev/null | jq -r 'sort_by(.x) | .[] | "\(.x)\t\(.name)"')

    local cur="" k; for k in "${order[@]}"; do cur+="${cur:+  ·  }${model[$k]} (${port[$k]})"; done
    local what
    what=$(ui_pick "Monitors, left → right now: $cur" "order" \
        "$( (( ${#desc[@]} == 2 )) && echo "Swap left and right::swap" || echo "Change the left → right order::order")" \
        "Choose which workspaces go on which monitor::ws" \
        "Back::back") || return 1
    [[ "$what" == back ]] && return 1

    if [[ "$what" == swap ]]; then
        order=("${order[1]}" "${order[0]}")
    elif [[ "$what" == order ]]; then
        local -a left=("${order[@]}") neworder=() opts=()
        local pos=1 pick
        while (( ${#left[@]} > 1 )); do
            opts=(); for k in "${left[@]}"; do opts+=("${model[$k]} (${port[$k]})::$k"); done
            pick=$(ui_pick "Which monitor is number $pos from the left?" "${left[0]}" "${opts[@]}") || return 1
            neworder+=("$pick")
            local -a rest=(); for k in "${left[@]}"; do [[ "$k" != "$pick" ]] && rest+=("$k"); done
            left=("${rest[@]}"); pos=$((pos + 1))
        done
        order=("${neworder[@]}" "${left[0]}")
    fi

    # Workspaces for each monitor, kept with the monitor when the order changes
    local -a wsl=()
    for k in "${order[@]}"; do
        local saved=""
        for i in "${!MON_DESC[@]}"; do [[ "${MON_DESC[$i]}" == "${desc[$k]}" ]] && saved="${MON_WSL[$i]}"; done
        wsl+=("$saved")
    done

    if [[ "$what" == ws ]]; then
        local how n=${#order[@]} per
        per=$(( WB_MAX_WS / n ))
        local even="" a=1
        for (( i = 0; i < n; i++ )); do
            local b=$(( i == n - 1 ? WB_MAX_WS : a + per - 1 ))
            even+="${even:+  ·  }${model[${order[$i]}]}: $a-$b"; a=$(( b + 1 ))
        done
        how=$(ui_pick "Workspaces per monitor" "even" \
            "Split evenly ($even)::even" \
            "Pick for each monitor::custom" \
            "No rule: a new workspace opens on the monitor you're on::none") || return 1
        case "$how" in
            even)
                wsl=(); a=1
                for (( i = 0; i < n; i++ )); do
                    local b=$(( i == n - 1 ? WB_MAX_WS : a + per - 1 ))
                    wsl+=("$a-$b"); a=$(( b + 1 ))
                done ;;
            none) for i in "${!wsl[@]}"; do wsl[$i]=""; done ;;
            custom)
                local used v exp dup
                while true; do
                    used=""; dup=""
                    for i in "${!order[@]}"; do
                        k=${order[$i]}
                        while true; do
                            v=$(ui_input "Workspaces on ${model[$k]} (${port[$k]}), e.g. 1-5 or 1 3 5 (empty = none)" "${wsl[$i]}") || return 1
                            exp=$(ws_expand "$v") && break
                            warn "'$v' isn't a list of workspaces 1-$WB_MAX_WS. Try again."
                        done
                        for w in $exp; do [[ " $used " == *" $w "* ]] && dup+=" $w"; done
                        used+=" $exp"; wsl[$i]="$v"
                    done
                    [[ -z "$dup" ]] && break
                    warn "Workspace(s)$dup are on more than one monitor. Each one can only be on one."
                    ui_pause
                done ;;
        esac
    fi

    # Positions: each monitor starts where the one to its left ends
    local x=0 out="" wsout=""
    for i in "${!order[@]}"; do
        k=${order[$i]}
        out+="${out:+;}${desc[$k]}|$x"; x=$(( x + width[$k] ))
        wsout+="${wsout:+;}${wsl[$i]}"
    done
    MONITORS="$out"; MON_WS="$wsout"
}

cmd_monitors() {
    state_load
    pick_monitors || return 0
    state_save
    apply_all
    mon_move_open_workspaces
    ok "Monitors: $(lbl_monitors | sed 's/^Monitors *//')"
    ui_pause
}
