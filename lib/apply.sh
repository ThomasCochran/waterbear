# lib/apply.sh — writes every config file from your saved settings + the chosen color scheme.
# Safe to run any time (`waterbear apply`): it only touches files Waterbear generates,
# never your override files (~/.config/hypr/user.lua, ~/.config/kitty/user.conf).

BACKUP_DIR="$HOME/.config/waterbear-backups"
MANAGED_DIRS=(hypr kitty rofi waybar gtk-3.0 gtk-4.0 xdg-desktop-portal swaync qt6ct)
MANAGED_FILES=(starship.toml)

# Before the first install: save the existing configs Waterbear will replace as the theme
# "old_theme" (~/.config/waterbear/old-theme, kept for good), or delete them.
prepare_old_configs() {  # prepare_old_configs save|delete
    local mode="$1" d found=false
    for d in "${MANAGED_DIRS[@]}" "${MANAGED_FILES[@]}"; do [[ -e "$HOME/.config/$d" ]] && found=true; done
    $found || return 0
    if [[ "$mode" == delete ]]; then
        for d in "${MANAGED_DIRS[@]}" "${MANAGED_FILES[@]}"; do rm -rf "${HOME:?}/.config/$d"; done
        info "Deleted old configs: ${MANAGED_DIRS[*]} ${MANAGED_FILES[*]}"
        return 0
    fi
    local dest="$OLD_THEME_DIR"
    [[ -d "$dest" ]] && dest="$BACKUP_DIR/$(date +%F_%H%M%S)"   # old_theme already saved: rotate a normal backup
    mkdir -p "$dest"
    for d in "${MANAGED_DIRS[@]}" "${MANAGED_FILES[@]}"; do [[ -e "$HOME/.config/$d" ]] && mv "$HOME/.config/$d" "$dest/"; done
    if [[ "$dest" == "$OLD_THEME_DIR" ]]; then
        info "Your old configs are saved as the theme 'old_theme' (Look & feel → Theme switches back to them)."
    else
        info "Old configs backed up to $dest"
        backups_trim
    fi
    return 0
}

backups_trim() {  # keep only the 3 newest backups
    local old; old=$(ls -1d "$BACKUP_DIR"/*/ 2>/dev/null | sort | head -n -3)
    [[ -n "$old" ]] && rm -rf $old && info "Removed older backups (keeping the newest 3)"
    return 0
}

# Switching to old_theme: Waterbear's configs are set aside in ~/.config/waterbear/waterbear-configs
# (your user.lua, kitty user.conf etc. come back with them), then your pre-Waterbear configs go back in place.
WB_SAVED_CONFIGS="$WB_CONF/waterbear-configs"
managed_move_to() {  # managed_move_to DIR — moves the configs Waterbear manages into DIR
    local d; mkdir -p "$1"
    for d in "${MANAGED_DIRS[@]}" "${MANAGED_FILES[@]}"; do [[ -e "$HOME/.config/$d" ]] && mv "$HOME/.config/$d" "$1/"; done
    return 0
}

old_theme_restore() {
    [[ -d "$OLD_THEME_DIR" ]] || { warn "There's no old_theme saved."; return 1; }
    rm -rf "$WB_SAVED_CONFIGS"
    managed_move_to "$WB_SAVED_CONFIGS"
    cp -a "$OLD_THEME_DIR/." "$HOME/.config/"
    ok "Your setup from before Waterbear is back in place."
}

# Leaving old_theme: what's there now (your old setup, maybe changed since) goes to a backup,
# Waterbear's own configs come back, then the new theme is written over them.
old_theme_leave() {
    local dest="$BACKUP_DIR/$(date +%F_%H%M%S)"
    managed_move_to "$dest"
    [[ -d "$WB_SAVED_CONFIGS" ]] && { cp -a "$WB_SAVED_CONFIGS/." "$HOME/.config/"; rm -rf "$WB_SAVED_CONFIGS"; }
    info "Your old setup as it was is backed up to $dest (old_theme itself stays saved)."
    backups_trim
}

link_bins() {  # helper scripts + the waterbear command go in ~/.local/bin (as links into Waterbear)
    mkdir -p "$WB_BIN"
    local f
    for f in "$WB_HOME"/bin/*; do ln -sf "$f" "$WB_BIN/$(basename "$f")"; done
    ln -sf "$WB_HOME/waterbear" "$WB_BIN/waterbear"
    webapps_fix_exec   # older web app launchers ran a bare `waterbear` (not on the desktop's PATH)
}

write_hypridle() {
    local s=$((IDLE_SAVER * 60)) l=$((IDLE_LOCK * 60)) o=$((IDLE_OFF * 60)) z=$((IDLE_SUSPEND * 60))
    local f="$HOME/.config/hypr/hypridle.conf"
    {
        echo "# ~/.config/hypr/hypridle.conf — generated by Waterbear (change it in: waterbear → System → Screensaver & lock)"
        echo "general {"
        echo "    lock_cmd = pidof hyprlock || hyprlock"
        echo "    before_sleep_cmd = loginctl lock-session"
        echo "    after_sleep_cmd = hyprctl dispatch 'hl.dsp.dpms({ action = \"enable\" })'"
        echo "}"
        if [[ "$SAVER" != off ]] && (( IDLE_SAVER < IDLE_LOCK )); then
            echo
            echo "# Screensaver ($SAVER)"
            echo "listener {"
            echo "    timeout = $s"
            echo "    on-timeout = ~/.local/bin/waterbear-screensaver"
            echo "    on-resume = pkill -f 'class waterbear-screensaver'"
            if [[ "$SAVER_ON_BATTERY" == no ]]; then
                echo "    # skipped on battery to save power (no battery = always runs)"
                echo "    condition_cmd = ! ls /sys/class/power_supply/BAT* > /dev/null 2>&1 || grep -qsx 1 /sys/class/power_supply/A*/online"
            fi
            echo "}"
        fi
        echo
        echo "listener {"
        echo "    timeout = $l"
        echo "    on-timeout = pkill -f 'class waterbear-screensaver'; loginctl lock-session"
        echo "}"
        echo
        echo "listener {"
        echo "    timeout = $o"
        echo "    on-timeout = hyprctl dispatch 'hl.dsp.dpms({ action = \"disable\" })'"
        echo "    on-resume = hyprctl dispatch 'hl.dsp.dpms({ action = \"enable\" })'"
        echo "}"
        if (( IDLE_SUSPEND > 0 )); then
            echo
            echo "listener {"
            echo "    timeout = $z"
            echo "    on-timeout = systemctl suspend"
            echo "}"
        fi
    } > "$f"
}

# The block Waterbear keeps in ~/.bashrc (everything between the markers is regenerated)
write_bashrc_block() {
    local rc="$HOME/.bashrc" tmp
    touch "$rc"
    tmp=$(mktemp)
    sed '/^# >>> waterbear >>>$/,/^# <<< waterbear <<<$/d' "$rc" > "$tmp"
    {
        echo "# >>> waterbear >>>"
        echo "# Managed by Waterbear — regenerated on every apply. Put your own lines outside this block."
        echo 'case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) export PATH="$HOME/.local/bin:$PATH" ;; esac'
        if has_app clock; then echo "alias clock='waterbear-clock'"; fi
        if has_app powertools; then
            echo "alias ls='eza --icons --group-directories-first'"
            echo "alias ll='eza -l --icons --git --group-directories-first'"
            echo "alias la='eza -la --icons --git --group-directories-first'"
            echo "alias cat='bat --paging=never --style=plain'"
            echo 'command -v zoxide > /dev/null && eval "$(zoxide init bash)"'
            echo 'command -v fzf > /dev/null && eval "$(fzf --bash)"'
        fi
        if [[ "$PROMPT" != off ]]; then
            echo 'command -v starship > /dev/null && eval "$(starship init bash)"'
        fi
        # fastfetch in every new kitty window (not in TTYs, ssh, editors' terminals or a bash started inside bash)
        echo 'if [[ $- == *i* && -n "${KITTY_WINDOW_ID:-}" && -z "${WB_FETCHED:-}" ]] && command -v fastfetch > /dev/null; then'
        echo '    export WB_FETCHED=1; fastfetch'
        echo 'fi'
        echo "# <<< waterbear <<<"
    } >> "$tmp"
    mv "$tmp" "$rc"
}

# fish's version of the bashrc block: a whole file in conf.d (fish loads it before config.fish,
# so your own ~/.config/fish/config.fish still wins). Written whenever fish is installed,
# so fish is themed even if you only start it by hand.
write_fish_config() {
    local f="$HOME/.config/fish/conf.d/waterbear.fish"
    if ! command -v fish > /dev/null; then rm -f "$f"; return 0; fi
    render fish/colors.fish "$f.colors"
    {
        echo "# ~/.config/fish/conf.d/waterbear.fish — generated by Waterbear, rewritten on every apply."
        echo "# Put your own settings in ~/.config/fish/config.fish (it loads after this file)."
        echo 'fish_add_path -g $HOME/.local/bin'
        echo 'status is-interactive; or return'
        echo
        echo 'set -g fish_greeting ""   # fastfetch is the greeting'
        echo 'set -gx SHELL (status fish-path)   # so tmux, yazi, etc. open fish too'
        if has_app clock; then echo "alias clock 'waterbear-clock'"; fi
        if has_app powertools; then
            echo "alias ls 'eza --icons --group-directories-first'"
            echo "alias ll 'eza -l --icons --git --group-directories-first'"
            echo "alias la 'eza -la --icons --git --group-directories-first'"
            echo "alias cat 'bat --paging=never --style=plain'"
            echo 'command -q zoxide; and zoxide init fish | source'
            echo 'command -q fzf; and fzf --fish | source'
        fi
        if [[ "$PROMPT" != off ]]; then
            echo 'command -q starship; and starship init fish | source'
        fi
        echo
        cat "$f.colors"
        echo
        echo '# fastfetch in every new kitty window (not in TTYs, ssh, editors'"'"' terminals or a shell started inside one)'
        echo 'if set -q KITTY_WINDOW_ID; and not set -q WB_FETCHED; and command -q fastfetch'
        echo '    set -gx WB_FETCHED 1; fastfetch'
        echo 'end'
    } > "$f"
    rm -f "$f.colors"
}

WALL_DIR="$HOME/.cache/waterbear/wallpaper"

screen_size() {  # biggest monitor in pixels, or 4K when not inside Hyprland (images are scaled to fit)
    local s=""
    command -v hyprctl > /dev/null && s=$(hyprctl monitors -j 2>/dev/null | jq -r 'max_by(.width * .height) | "\(.width) \(.height)"' 2>/dev/null)
    [[ "$s" =~ ^[0-9]+\ [0-9]+$ ]] && echo "$s" || echo "3840 2160"
}

hex_to_unit() {  # ff8800 -> "1.0000 0.5333 0.0000"
    awk -v r=$((16#${1:0:2})) -v g=$((16#${1:2:2})) -v b=$((16#${1:4:2})) \
        'BEGIN { printf "%.4f %.4f %.4f", r / 255, g / 255, b / 255 }'
}

# Your own picture as the background (WALLPAPER=picture): scaled to cover the screen
picture_svg() {  # picture_svg FILE W H
    local ext="${1##*.}"
    cp "$1" "$WALL_DIR/picture-src.$ext"
    cat > "$WALL_DIR/wall.svg" << SVG
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="$2" height="$3" viewBox="0 0 $2 $3">
  <rect width="$2" height="$3" fill="#$P_BG"/>
  <image xlink:href="picture-src.$ext" href="picture-src.$ext" x="0" y="0" width="$2" height="$3" preserveAspectRatio="xMidYMid slice"/>
</svg>
SVG
}

# Your own image wins over the bundled waterbear: ~/.config/waterbear/logo.svg / .png / .jpg
logo_source() {
    local f
    for f in "$WB_CONF/logo.svg" "$WB_CONF/logo.png" "$WB_CONF/logo.jpg" "$WB_HOME/wallpapers/waterbear.png"; do
        [[ -f "$f" ]] && { echo "$f"; return; }
    done
}

wallpaper_generate() {
    rm -rf "$WALL_DIR"; mkdir -p "$WALL_DIR"
    case "$WALLPAPER" in grid|orbit|logo|picture) ;; *) return 0 ;; esac
    if [[ "$WALLPAPER" == picture && ! -f "$WALL_IMAGE" ]]; then
        warn "Your background picture is missing ($WALL_IMAGE); using the solid background."; return 0
    fi
    command -v rsvg-convert > /dev/null || { warn "rsvg-convert missing (sudo pacman -S librsvg); using the solid background."; return 0; }
    local w h; read -r w h <<< "$(screen_size)"
    if [[ "$WALLPAPER" == picture ]]; then
        picture_svg "$WALL_IMAGE" "$w" "$h"
    elif [[ "$WALLPAPER" == logo ]]; then
        # Gradient map: the image's darkest shade becomes the theme background, white becomes the accent
        local src ext r1 g1 b1 r2 g2 b2
        src=$(logo_source); ext="${src##*.}"
        cp "$src" "$WALL_DIR/logo-src.$ext"
        read -r r1 g1 b1 <<< "$(hex_to_unit "$P_BG")"
        read -r r2 g2 b2 <<< "$(hex_to_unit "$P_RAIN")"
        cat > "$WALL_DIR/wall.svg" << SVG
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="$w" height="$h" viewBox="0 0 $w $h">
  <defs>
    <filter id="map" color-interpolation-filters="sRGB" x="0" y="0" width="100%" height="100%">
      <feColorMatrix type="matrix" values="0.2126 0.7152 0.0722 0 0  0.2126 0.7152 0.0722 0 0  0.2126 0.7152 0.0722 0 0  0 0 0 1 0"/>
      <feComponentTransfer>
        <feFuncR type="table" tableValues="$r1 $r2"/>
        <feFuncG type="table" tableValues="$g1 $g2"/>
        <feFuncB type="table" tableValues="$b1 $b2"/>
      </feComponentTransfer>
    </filter>
  </defs>
  <rect width="$w" height="$h" fill="#$P_BG"/>
  <image xlink:href="logo-src.$ext" href="logo-src.$ext" x="0" y="0" width="$w" height="$h" preserveAspectRatio="xMidYMid meet" filter="url(#map)"/>
</svg>
SVG
    else
        render "wallpapers/$WALLPAPER.svg" "$WALL_DIR/wall.svg"
        sed -i "s/@@W@@/$w/; s/@@H@@/$h/" "$WALL_DIR/wall.svg"
    fi
    (cd "$WALL_DIR" && rsvg-convert wall.svg -o wallpaper.png) || { warn "Couldn't draw the wallpaper; using the solid background."; rm -f "$WALL_DIR/wallpaper.png"; }
}

write_wallpaper_configs() {
    local cache="$HOME/.cache/waterbear"
    mkdir -p "$cache"
    # Colors for the runtime scripts (live wallpaper, screensaver)
    printf 'P_BG=%s\nP_FG=%s\nP_A=%s\nP_B=%s\nP_RAIN=%s\n' "$P_BG" "$P_FG" "$P_A" "$P_B" "$P_RAIN" > "$cache/palette.sh"
    render cava/wallpaper.conf "$cache/cava-wallpaper.conf"
    {
        echo "# ~/.config/hypr/hyprpaper.conf — generated by Waterbear"
        echo "splash = false"
        echo "ipc = true"
        echo "wallpaper {"
        echo "    monitor ="
        echo "    path = $WALL_DIR/wallpaper.png"
        echo "    fit_mode = cover"
        echo "}"
    } > "$HOME/.config/hypr/hyprpaper.conf"
    # Lock screen: blurred, dimmed copy of the wallpaper (static wallpapers only)
    if [[ "$LOCK_BG" == wallpaper && -f "$WALL_DIR/wallpaper.png" ]]; then
        sed -i "/^background {/,/^}/ s|^    color = .*|&\n    path = $WALL_DIR/wallpaper.png\n    blur_passes = 3\n    blur_size = 8\n    brightness = 0.55|" "$HOME/.config/hypr/hyprlock.conf"
    fi
}

# Folder icons in your theme's colors: Papirus, with its blue folders recolored to the accent.
# The renamed copies are made once (and again when Papirus updates); each theme change only recolors them.
ICON_DIR="$HOME/.local/share/icons/Waterbear"
write_icon_theme() {
    local src=/usr/share/icons/Papirus cache="$HOME/.cache/waterbear/icon-src" ver d size f base
    T_ICONS=Adwaita
    if [[ ! -d "$src" ]]; then rm -rf "$ICON_DIR"; return 0; fi
    # v2: every standard name (folder-publicshare for ~/Public, user-desktop…), not just the folder-blue-* files
    ver="v2 $(pacman -Q papirus-icon-theme 2> /dev/null || echo unknown)"
    if [[ "$(cat "$cache/.version" 2> /dev/null)" != "$ver" ]]; then
        rm -rf "$cache"
        # Papirus's other folder colors (folder-red-*, folder-bluegrey-*…) are skipped; the plain names
        # (folder.svg, folder-publicshare.svg…) all lead to its default blue ones, which get recolored.
        local colors='adwaita|black|blue|bluegrey|breeze|brown|carmine|cyan|darkcyan|deeporange|green|grey|indigo|magenta|nordic|orange|palebrown|paleorange|pink|red|teal|violet|white|yaru|yellow'
        for d in "$src"/*x*; do
            [[ -L "$d" || ! -d "$d/places" ]] && continue
            size=${d##*/}
            mkdir -p "$cache/$size/places"
            for f in "$d"/places/folder*.svg "$d"/places/user-*.svg; do
                base=${f##*/}
                [[ "$base" =~ ^(folder|user)-($colors)(-|\.svg$) ]] && continue
                [[ -e "$f" ]] && cp -L "$f" "$cache/$size/places/$base"
            done
        done
        echo "$ver" > "$cache/.version"
    fi
    rm -rf "$ICON_DIR"; mkdir -p "$ICON_DIR"
    cp -a "$cache/." "$ICON_DIR/"; rm -f "$ICON_DIR/.version"
    find "$ICON_DIR" -name '*.svg' -exec sed -i -e "s/#5294e2/#$P_A/gI" -e "s/#4877b1/#$(hex_darken "$P_A" 15)/gI" \
        -e "s/#1d344f/#$(hex_darken "$P_A" 65)/gI" {} +
    local dirs=() entries=""
    for d in "$ICON_DIR"/*x*; do
        size=${d##*/}; dirs+=("$size/places")
        entries+=$'\n'"[$size/places]"$'\n'"Context=Places"$'\n'"Size=${size%%x*}"$'\n'"Type=Fixed"$'\n'
    done
    {
        echo "[Icon Theme]"
        echo "Name=Waterbear"
        echo "Comment=Papirus with folders in your Waterbear theme's colors (generated, rewritten on every theme change)"
        echo "Inherits=$T_PAPIRUS,hicolor"
        echo "Example=folder"
        echo "Directories=$(IFS=,; echo "${dirs[*]}")"
        printf '%s' "$entries"
    } > "$ICON_DIR/index.theme"
    command -v gtk-update-icon-cache > /dev/null && gtk-update-icon-cache -q -f -t "$ICON_DIR" 2> /dev/null
    T_ICONS=Waterbear
}

palette_is_dark() {  # true when the loaded theme's background is dark
    local r=$((16#${P_BG:0:2})) g=$((16#${P_BG:2:2})) b=$((16#${P_BG:4:2}))
    (( r * 299 + g * 587 + b * 114 < 128000 ))
}

# GTK 3 + 4: every app in the theme's colors. If dark mode doesn't match the theme
# (light mode with a dark theme, or the other way), apps keep plain Adwaita and only take the accent.
write_gtk() {
    local full=no g3="$HOME/.config/gtk-3.0" g4="$HOME/.config/gtk-4.0" tmp
    if palette_is_dark; then [[ "$DARK_MODE" == yes ]] && full=yes; else [[ "$DARK_MODE" != yes ]] && full=yes; fi
    render gtk/settings.ini "$g3/settings.ini"
    render gtk/settings.ini "$g4/settings.ini"
    tmp=$(mktemp -d)
    if [[ "$full" == yes ]]; then
        render gtk/gtk3-all.css "$tmp/a"; render gtk/thunar.css "$tmp/b"
        render gtk/gtk4.css "$g4/gtk.css"
    else
        render gtk/gtk3-accent.css "$tmp/a"; : > "$tmp/b"
        render gtk/gtk4-accent.css "$g4/gtk.css"
    fi
    {
        echo "/* ~/.config/gtk-3.0/gtk.css — generated by Waterbear ($P_NAME). Rewritten on every theme change."
        echo "   Your own CSS goes in user.css (loaded last, so it wins). */"
        cat "$tmp/a" "$tmp/b"
        echo '@import url("user.css");'
    } > "$g3/gtk.css"
    rm -rf "$tmp"
    echo '@import url("user.css");' >> "$g4/gtk.css"
    [[ -f "$g3/user.css" ]] || echo "/* ~/.config/gtk-3.0/user.css — your GTK 3 CSS (never overwritten; loads after Waterbear's) */" > "$g3/user.css"
    [[ -f "$g4/user.css" ]] || echo "/* ~/.config/gtk-4.0/user.css — your GTK 4 CSS (never overwritten; loads after Waterbear's) */" > "$g4/user.css"
}

write_qt() {  # Qt 6 apps through qt6ct, with the theme's colors
    local d="$HOME/.config/qt6ct"
    render qt6ct/waterbear.conf "$d/colors/waterbear.conf"
    {
        echo "# ~/.config/qt6ct/qt6ct.conf — generated by Waterbear"
        echo "[Appearance]"
        echo "color_scheme_path=$d/colors/waterbear.conf"
        echo "custom_palette=true"
        echo "icon_theme=$T_ICONS"
        echo "style=Fusion"
        echo "standard_dialogs=default"
    } > "$d/qt6ct.conf"
}

apply_all() {
    if [[ "$DESKTOP" != yes ]]; then
        desktop_needed || true
        return 0
    fi
    if [[ "$SCHEME" == old_theme ]]; then
        # Your pre-Waterbear configs are in place; leave them alone
        link_bins
        reload_desktop
        return 0
    fi
    scheme_load "$SCHEME"
    link_bins
    local H="$HOME/.config/hypr"

    # Hyprland
    ap_step "Folder icons"
    write_icon_theme   # first: sets T_ICONS, used by the templates below
    ap_step "Hyprland"
    render hypr/hyprland.lua "$H/hyprland.lua"
    if [[ "$MENU_KEY" == yes ]]; then sed -i 's/   -- @@MENU_KEY@@$//' "$H/hyprland.lua"
    else sed -i 's/^\(hl.bind("SUPER + ALT + space".*\)   -- @@MENU_KEY@@$/-- (turned off in the menu) \1/' "$H/hyprland.lua"; fi
    write_monitors_lua
    render "hypr/binds-$KEYBINDS.lua" "$H/binds.lua"
    render hypr/hyprlock.conf "$H/hyprlock.conf"
    ap_step "Background ($WALLPAPER)"
    wallpaper_generate
    write_wallpaper_configs
    render "hypr/KEYBINDS-$KEYBINDS.md" "$H/KEYBINDS.md"   # cheat sheet for the chosen keybind set
    write_hypridle
    [[ -f "$H/user.lua" ]] || cat > "$H/user.lua" << 'EOF'
-- ~/.config/hypr/user.lua — YOUR file. Waterbear creates it once and never changes it.
-- It loads after Waterbear's config, so anything here wins. Examples:
--
-- hl.bind("SUPER + F1", hl.dsp.exec_cmd("firefox --private-window"))
-- hl.config({ general = { gaps_out = 4 } })
-- hl.monitor({ output = "eDP-1", mode = "1920x1080@60", position = "0x0", scale = 1 })
EOF

    ap_step "Terminal, launcher, GTK and Qt apps, notifications"
    # Terminal, launcher, GTK, portal
    render kitty/kitty.conf "$HOME/.config/kitty/kitty.conf"
    # Shell: kitty runs fish, but your login shell stays bash (Hyprland starts from ~/.bash_profile on tty1)
    if [[ "$USER_SHELL" == fish ]] && command -v fish > /dev/null; then
        sed -i "s|^# Your own settings|# Shell (change it in: waterbear → Shell)\nshell $(command -v fish)\n\n&|" "$HOME/.config/kitty/kitty.conf"
    fi
    [[ -f "$HOME/.config/kitty/user.conf" ]] || echo "# ~/.config/kitty/user.conf — your kitty settings (never overwritten)" > "$HOME/.config/kitty/user.conf"
    render rofi/config.rasi "$HOME/.config/rofi/config.rasi"
    render rofi/neon.rasi "$HOME/.config/rofi/neon.rasi"
    write_gtk
    write_qt
    render swaync/style.css "$HOME/.config/swaync/style.css"
    render portal/hyprland-portals.conf "$HOME/.config/xdg-desktop-portal/hyprland-portals.conf"

    ap_step "Status bar ($BAR)"
    # Status bar
    rm -rf "$HOME/.config/waybar"
    if [[ "$BAR" != none ]]; then
        render "waybar/$BAR/config.jsonc" "$HOME/.config/waybar/config.jsonc"
        render "waybar/$BAR/style.css" "$HOME/.config/waybar/style.css"
    fi

    ap_step "Prompt and shell"
    # Prompt
    if [[ "$PROMPT" != off ]]; then
        render "starship/$PROMPT.toml" "$HOME/.config/starship.toml"
    fi
    write_bashrc_block
    write_fish_config

    ap_step "App themes (btop, Neovim)"
    # btop theme
    if has_app btop; then
        render btop/waterbear.theme "$HOME/.config/btop/themes/waterbear.theme"
        local bc="$HOME/.config/btop/btop.conf"
        if [[ -f "$bc" ]] && grep -q '^color_theme' "$bc"; then
            sed -i 's|^color_theme = .*|color_theme = "waterbear"|' "$bc"
        elif [[ -f "$bc" ]]; then
            echo 'color_theme = "waterbear"' >> "$bc"
        else
            mkdir -p "$(dirname "$bc")"; printf 'color_theme = "waterbear"\ntheme_background = True\n' > "$bc"
        fi
    fi

    # Neovim (LazyVim) theme
    if [[ -d "$HOME/.config/nvim/lua/plugins" ]]; then
        render nvim/waterbear-theme.lua "$HOME/.config/nvim/lua/plugins/waterbear-theme.lua"
    fi

    reload_desktop
}

# Make running programs pick up the new files (only when inside Hyprland)
reload_desktop() {
    [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]] || return 0
    # NVIDIA driver updated but not restarted yet: anything restarted now (bar, background, terminals)
    # would load driver files that don't match the running driver and show up black. Leave it all running.
    if nvidia_stale; then
        warn "Not reloading the desktop: the NVIDIA driver was updated. The new configs show after a restart."
        return 0
    fi
    ap_step "Reloading the desktop"
    # Each one gets a time limit and no keyboard: a program that hangs can't stop the update
    rd 10 hyprctl reload
    (setsid "$WB_BIN/waterbear-bar" < /dev/null > /dev/null 2>&1 &)   # restarts the bar, or just stops it if there's none
    pkill -x hypridle 2> /dev/null || true; (setsid hypridle < /dev/null > /dev/null 2>&1 &)
    rd 20 "$WB_BIN/waterbear-wallpaper"
    pkill -USR1 -x kitty 2> /dev/null || true   # kitty reloads its config on SIGUSR1
    if pgrep -x swaync > /dev/null; then rd 5 swaync-client -sw -rs; fi   # notification colors (-sw: never wait for swaync)
    if command -v gsettings > /dev/null; then
        rd 5 gsettings set org.gnome.desktop.interface color-scheme "$T_CS"
        rd 5 gsettings set org.gnome.desktop.interface gtk-theme "$T_GTK"
        rd 5 gsettings set org.gnome.desktop.interface icon-theme "${T_ICONS:-Adwaita}"
    fi
    # Thunar keeps its old icons and colors until it restarts
    if pgrep -x thunar > /dev/null; then rd 5 thunar -q; fi
    return 0
}

rd() {  # rd SECONDS COMMAND... — run a reload command with a time limit; never fails
    local t="$1"; shift
    ap_step "  ${1##*/} ${2:-}"
    command -v "$1" > /dev/null || return 0
    timeout -k 2 "$t" "$@" < /dev/null > /dev/null 2>&1 || { local rc=$?; (( rc == 124 || rc == 137 )) && ap_step "    (took longer than ${t}s, skipped)"; }
    return 0
}

ap_step() { [[ "${APPLY_VERBOSE:-false}" == true ]] && info "$1"; return 0; }   # progress, when run in a terminal
